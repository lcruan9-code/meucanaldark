#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadChannel } from "./lib/channel.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");

function parseArgs() {
  const args = process.argv.slice(2);
  let projectId = null;

  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--project" && args[i + 1]) {
      projectId = args[++i];
    } else if (!args[i].startsWith("--") && !projectId) {
      projectId = args[i];
    }
  }

  if (!projectId) {
    console.error("Usage: node scripts/compose.mjs <project-id>");
    process.exit(1);
  }

  return { projectId };
}

/**
 * Regenerates src/projects.ts with static imports for all directories in projects/ that contain project.json
 */
export function updateProjectsRegistry() {
  const projectsDir = path.resolve(ROOT, "projects");
  const entries = fs.readdirSync(projectsDir, { withFileTypes: true });

  const validProjects = [];
  for (const entry of entries) {
    if (entry.isDirectory()) {
      const projJson = path.resolve(projectsDir, entry.name, "project.json");
      if (fs.existsSync(projJson)) {
        // Also ensure durations.json exists
        const durJson = path.resolve(projectsDir, entry.name, "durations.json");
        if (!fs.existsSync(durJson)) {
          fs.writeFileSync(durJson, "{}\n", "utf-8");
        }
        validProjects.push(entry.name);
      }
    }
  }

  // Sort to have deterministic output
  validProjects.sort();

  function toVarName(name) {
    return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  }

  let code = `/**
 * Autogenerated projects registry for Remotion Studio & CLI render.
 * Updated automatically by scripts/compose.mjs
 */

import type { NarrationDurations } from "./engine/timeline";

`;

  for (const p of validProjects) {
    const varName = toVarName(p);
    code += `import ${varName} from "../projects/${p}/project.json";\n`;
    code += `import ${varName}Durations from "../projects/${p}/durations.json";\n`;
  }

  code += `\nexport type ProjectEntry = {\n  raw: unknown;\n  durations: NarrationDurations;\n};\n\n`;
  code += `export const PROJECTS: readonly ProjectEntry[] = [\n`;

  for (const p of validProjects) {
    const varName = toVarName(p);
    code += `  { raw: ${varName}, durations: ${varName}Durations as NarrationDurations },\n`;
  }

  code += `];\n`;

  const targetFile = path.resolve(ROOT, "src", "projects.ts");
  fs.writeFileSync(targetFile, code, "utf-8");
  console.log(`[compose] Updated src/projects.ts with ${validProjects.length} projects (${validProjects.join(", ")})`);
}

export async function runCompose({ projectId }) {
  const start = Date.now();
  console.log(`[compose] Composing project.json for: ${projectId}`);

  const projectDir = path.resolve(ROOT, "projects", projectId);
  const storyboardFile = path.resolve(projectDir, "storyboard.json");

  if (!fs.existsSync(storyboardFile)) {
    throw new Error(`[compose] storyboard.json not found at ${storyboardFile}`);
  }

  const storyboard = JSON.parse(fs.readFileSync(storyboardFile, "utf-8"));
  const channelId = storyboard.channelId || "invisible-systems";
  const channel = loadChannel(channelId);

  // Optional narrative.json to get chapter titles
  const narrativeFile = path.resolve(projectDir, "narrative.json");
  let narrative = null;
  if (fs.existsSync(narrativeFile)) {
    narrative = JSON.parse(fs.readFileSync(narrativeFile, "utf-8"));
  }

  // Load durations if already measured
  const durJson = path.resolve(projectDir, "durations.json");
  let durations = {};
  if (fs.existsSync(durJson)) {
    try {
      durations = JSON.parse(fs.readFileSync(durJson, "utf-8"));
    } catch {}
  }

  // Build scenes list
  const scenes = [];
  const chapterFirstScene = new Map();

  for (const s of storyboard.plannedScenes) {
    if (s.chapterId && !chapterFirstScene.has(s.chapterId)) {
      chapterFirstScene.set(s.chapterId, s.sceneId);
    }

    if (s.sequenceType) {
      scenes.push({
        sequence: s.sequenceType,
        id: s.sceneId,
        params: s.sequenceParams || {},
      });
    } else if (s.layers) {
      const relSrc = `narration/${projectId}/${s.sceneId}.mp3`;
      const sceneObj = {
        id: s.sceneId,
        ...(s.chapterId ? { chapterId: s.chapterId } : {}),
        ...(s.transitionIn ? { transitionIn: s.transitionIn } : {}),
        note: s.note || "",
        layers: s.layers,
      };

      if (durations[relSrc]) {
        sceneObj.narration = {
          src: relSrc,
          text: s.narrationText || "",
          gainDb: 0,
        };
      } else {
        sceneObj.duration = s.estimatedDurationSeconds || 5;
      }

      scenes.push(sceneObj);
    }
  }

  // Build chapters metadata matching zChapter: { id: string, title: string }
  const chapters = [];
  if (narrative?.chapters) {
    for (const ch of narrative.chapters) {
      chapters.push({
        id: ch.id,
        title: ch.title,
      });
    }
  }

  const projectJson = {
    schemaVersion: 1,
    id: projectId,
    title: narrative?.title || storyboard.projectId || projectId,
    language: narrative?.language || "en",
    width: 1920,
    height: 1080,
    fps: 30,
    theme: {
      palette: channel.theme?.palette || {
        bg: "#070d16",
        ink: "#f2f5f8",
        muted: "#8b97a8",
        accent: "#39d0d8",
        accentWarm: "#f5a524",
        grid: "#12202e",
      },
      grain: channel.theme?.grain ?? 0.07,
      vignette: channel.theme?.vignette ?? 0.45,
    },
    audio: channel.audio || {
      musicGainDb: -22,
      duckDb: -9,
      masterGainDb: 0,
    },
    ...(chapters.length > 0 ? { chapters } : {}),
    scenes,
  };

  // Ensure durations.json exists
  if (!fs.existsSync(durJson)) {
    fs.writeFileSync(durJson, "{}\n", "utf-8");
  }

  const outFile = path.resolve(projectDir, "project.json");
  fs.writeFileSync(outFile, JSON.stringify(projectJson, null, 2), "utf-8");

  // Update src/projects.ts
  updateProjectsRegistry();

  const elapsed = ((Date.now() - start) / 1000).toFixed(2);
  console.log(`[compose] ✓ Done in ${elapsed}s -> ${outFile}`);
  return { outFile, projectJson };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { projectId } = parseArgs();
  runCompose({ projectId }).catch((err) => {
    console.error(`[compose] ✗ Error:`, err);
    process.exit(1);
  });
}
